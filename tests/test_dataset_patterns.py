def _found(text: str) -> list[tuple[str, list[str]]]:
    entities = ENGINE.detect(text, POLICY.pd_types, POLICY.combinations)
    return [(e.pd_type.value, [text[start:end] for start, end in e.parts]) for e in entities]


@pytest.mark.parametrize(("text", "expected"), CASES, ids=[c[0] for c in CASES])
def test_dataset_pattern(text: str, expected: list[tuple[str, list[str]]] | None) -> None:
    assert _found(text) == (expected or [])
