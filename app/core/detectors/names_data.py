FIRST_NAMES: frozenset[str] = frozenset((_MALE_NAMES + _FEMALE_NAMES).split())

_STEM_ENDINGS = ("ия", "ья", "а", "я", "й", "ь", "о")
_CASE_ENDINGS = ("ой", "ей", "ом", "ем", "ию", "ии", "ья", "ью", "ье", "а", "у", "е", "ы", "и", "ю", "я")

# Основы, совпадающие с частыми словами и аббревиатурами («ИНН», «май»).
_STEM_BLOCKLIST = frozenset({"инн", "май", "марк"})


def _stem(name: str) -> str:
    for ending in _STEM_ENDINGS:
        if name.endswith(ending) and len(name) - len(ending) >= 3:
            return name[: -len(ending)] + ("и" if ending == "ия" else "")
    return name


FIRST_NAME_STEMS: frozenset[str] = frozenset(_stem(n) for n in FIRST_NAMES) - _STEM_BLOCKLIST


def is_first_name(word_lower: str) -> bool:
    """Имя в любом падеже: «Иван», «Ивана», «Марии», «Анной»."""
    if word_lower in _STEM_BLOCKLIST:
        return False
    if word_lower in FIRST_NAMES or word_lower in FIRST_NAME_STEMS:
        return True
    return any(
        word_lower.endswith(ending) and word_lower[: -len(ending)] in FIRST_NAME_STEMS
        for ending in _CASE_ENDINGS
    )


